CREATE TABLE task_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    object_key VARCHAR(512) NOT NULL UNIQUE CHECK (btrim(object_key) <> ''),
    file_name VARCHAR(255) NOT NULL CHECK (btrim(file_name) <> ''),
    content_type VARCHAR(255) NOT NULL CHECK (btrim(content_type) <> ''),
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    etag VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_task_attachments_task_id ON task_attachments(task_id, id);

CREATE TRIGGER task_attachments_updated_at BEFORE UPDATE ON task_attachments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
